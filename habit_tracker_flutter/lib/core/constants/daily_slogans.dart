  /// Returns a unique slogan based on the date.
  /// Uses a deterministic hash of year, month, and day to guarantee a fresh quote daily.
  static String getSloganForDate(DateTime date) {
    final dayOfYear = date.difference(DateTime(date.year, 1, 1)).inDays;
    // Mix year and dayOfYear to avoid repeating the exact sequence across years
    final index = (dayOfYear + (date.year * 7)) % slogans.length;
    return slogans[index];
  }

  /// Get next slogan offset (for manual tap-to-shuffle)
  static String getSloganWithOffset(DateTime date, int offset) {
    final dayOfYear = date.difference(DateTime(date.year, 1, 1)).inDays;
    final index = (dayOfYear + (date.year * 7) + offset) % slogans.length;
    return slogans[index];
  }
